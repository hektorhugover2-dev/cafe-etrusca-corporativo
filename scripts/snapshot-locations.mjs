// Snapshot of https://cafeetrusca.com/api/Location → src/app/shared/kernel/data/locations.data.ts
// (+ course-venues.data.ts). The sucursales change rarely, so the app uses these static files
// (selector, city mapping, addresses, course × sucursal city pages) instead of calling
// /api/Location on every page. Only /api/Event stays live (dates change).
// Refresh:  node scripts/snapshot-locations.mjs   (review the diff, then rebuild; a new
// "Sucursal …" automatically gets its course city pages, sitemap entries and prerender).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const API = 'https://cafeetrusca.com/api/Location';
const OUT = fileURLToPath(new URL('../src/app/shared/kernel/data/locations.data.ts', import.meta.url));
// Tiny id/label/slug table of the course venues: imported by the (eager) route/sitemap code to
// build the course × sucursal city pages without pulling the full addresses into main.js.
const OUT_VENUES = fileURLToPath(new URL('../src/app/shared/kernel/data/course-venues.data.ts', import.meta.url));

const clean = (v) => String(v ?? '').replace(/\s+/g, ' ').trim();
const norm = (v) => clean(v).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
const slugify = (v) => norm(v).replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/** "Sucursal Zona Rosa" (city CDMX) → "Zona Rosa CDMX"; "Sucursal León" → "León" (old site's city-page naming). */
function venueLabel(l) {
  const base = clean(l.name).replace(/^sucursal\s+/i, '');
  return norm(l.city) === 'cdmx' && !/\bcdmx\b/i.test(base) ? `${base} CDMX` : base;
}

/** One readable address line built only from the API fields (no invented data). */
function displayAddress(l) {
  const parts = [clean(l.locationAdress).replace(/[,\s]+$/, '')];
  const has = (s) => norm(parts.join(', ')).includes(norm(s));
  const region = clean(l.addressRegion);
  if (region && region.length < 40 && !has(region)) parts.push(region);
  const city = clean(l.city);
  if (city && !has(city)) parts.push(city);
  const cp = clean(l.postalCode);
  if (cp && !has(cp)) parts.push(`C.P. ${cp}`);
  return parts.filter(Boolean).join(', ');
}

const res = await fetch(API, { headers: { Accept: 'application/json' } });
if (!res.ok) throw new Error(`${API} → HTTP ${res.status}`);
const list = await res.json();

const rows = list
  .map((l) => ({
    id: Number(l.id),
    name: clean(l.name),
    slug: clean(l.slug),
    // Course venues: the "Sucursal …" entries (distribuidores, CEDIS and the roasting plant are not).
    courseVenue: /^sucursal\b/i.test(clean(l.name)),
    venueLabel: venueLabel(l),
    venueSlug: slugify(venueLabel(l)),
    city: clean(l.city),
    state: clean(l.state),
    address: clean(l.locationAdress).replace(/[,\s]+$/, ''),
    addressRegion: clean(l.addressRegion),
    postalCode: clean(l.postalCode),
    displayAddress: displayAddress(l),
    telephone: clean(l.telephone),
    email: clean(l.email),
    emailB: clean(l.emailB),
    mapsUrl: clean(l.url),
    mapsEmbed: clean(l.urlEmbed),
    latitude: clean(l.latitude),
    longitude: clean(l.longitude),
    image: clean(l.image)
  }))
  .sort((a, b) => a.id - b.id);

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `/**
 * Sucursales / ubicaciones de Café Etrusca — snapshot de ${API} (${today}).
 * GENERATED by scripts/snapshot-locations.mjs; do not edit by hand.
 * Refresh: \`node scripts/snapshot-locations.mjs\`, review the diff, rebuild.
 * Used by the legacy course pages (sucursal selector, default city, "Sede" block, Course
 * JSON-LD location) so the site does not call /api/Location on every page; event dates
 * still come live from /api/Event.
 */
export interface EtruscaLocation {
  /** Same id as locationId in /api/Event. */
  id: number;
  name: string;
  slug: string;
  /** "Sucursal …" entries: the only ones that host courses/talleres. */
  courseVenue: boolean;
  /** City-page label (e.g. "Zona Rosa CDMX", "León"). */
  venueLabel: string;
  /** City-page slug (e.g. "zona-rosa-cdmx", "leon"): <course>-en-<venueSlug>. */
  venueSlug: string;
  city: string;
  state: string;
  address: string;
  addressRegion: string;
  postalCode: string;
  /** address + region/city/C.P. when not already in it (API fields only). */
  displayAddress: string;
  telephone: string;
  email: string;
  emailB: string;
  mapsUrl: string;
  /** Google Maps embed "pb" parameter (https://www.google.com/maps/embed?pb=…). */
  mapsEmbed: string;
  latitude: string;
  longitude: string;
  image: string;
}

export const ETRUSCA_LOCATIONS: ReadonlyArray<EtruscaLocation> = ${JSON.stringify(rows, null, 2)};

/** Sucursales that host courses (selector options). */
export const COURSE_VENUES: ReadonlyArray<EtruscaLocation> = ETRUSCA_LOCATIONS.filter((l) => l.courseVenue);

export function locationById(id: number | null | undefined): EtruscaLocation | undefined {
  return ETRUSCA_LOCATIONS.find((l) => l.id === Number(id));
}
`,
  'utf8'
);

const venues = rows.filter((r) => r.courseVenue).map((r) => ({ id: r.id, label: r.venueLabel, slug: r.venueSlug }));
writeFileSync(
  OUT_VENUES,
  `/**
 * Course venues (sucursales): id, city-page label and slug. GENERATED by
 * scripts/snapshot-locations.mjs from ${API} (${today}); refresh with that script.
 * Full data (address, phone, map) lives in locations.data.ts.
 */
export interface CourseVenue {
  id: number;
  label: string;
  slug: string;
}

export const COURSE_VENUE_LIST: ReadonlyArray<CourseVenue> = ${JSON.stringify(venues, null, 2)};
`,
  'utf8'
);
console.log(`${rows.length} locations (${venues.length} course venues) → ${OUT}`);
