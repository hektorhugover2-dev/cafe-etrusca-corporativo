// Keeps src/app/domains/education/presentation/event-archive.data.ts: every /cursos-y-talleres/<slug>
// event ever seen by a build (live /api/Event + public/data/events.json), with its categoryId and
// locationId. /api/Event only lists UPCOMING dates, so once a date passes the API forgets it; this
// archive lets the next builds 301 that URL to its course page (seo-redirects.ts → web.config, server.ts).
// Runs in "prebuild" (npm run build). Entries are never removed (old URLs keep their 301).
// Usage (from repo root): node scripts/update-event-archive.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { importTs } from './_load-ts.mjs';

const FILE = 'src/app/domains/education/presentation/event-archive.data.ts';
const { loadEvents, readEventsSnapshot, eventSlug } = await importTs('src/events-snapshot.server.ts');

const byslug = new Map();
if (existsSync(FILE)) {
  const m = readFileSync(FILE, 'utf8').match(/EVENT_ARCHIVE[^=]*=\s*(\[[\s\S]*\]);/);
  if (!m) throw new Error(`${FILE}: cannot parse EVENT_ARCHIVE`);
  for (const e of JSON.parse(m[1])) byslug.set(e.slug, e);
}
const before = byslug.size;
const num = (v) => (Number(v) > 0 ? Number(v) : null);
const add = (e) => {
  const slug = eventSlug(e);
  if (!slug) return;
  byslug.set(slug, {
    slug,
    categoryId: num(e.categoryId ?? e.category?.id),
    locationId: num(e.locationId ?? e.location?.id),
    title: String(e.category?.name || e.title || '').replace(/\s+/g, ' ').trim(),
    start: String(e.start || ''),
    end: String(e.end || e.start || '')
  });
};
for (const e of await readEventsSnapshot()) add(e);
const { events, source } = await loadEvents();
for (const e of events) add(e);

const list = [...byslug.values()].sort((a, b) => a.start.localeCompare(b.start) || a.slug.localeCompare(b.slug));
const body = `// GENERATED by scripts/update-event-archive.mjs (prebuild). Do not edit by hand.
// Every /cursos-y-talleres/<slug> event seen by a build: past ones get a 301 to their course page.
export interface ArchivedEvent {
  slug: string;
  categoryId: number | null;
  locationId: number | null;
  title: string;
  start: string;
  end: string;
}

export const EVENT_ARCHIVE: ReadonlyArray<ArchivedEvent> = [
${list.map((e) => '  ' + JSON.stringify(e)).join(',\n')}
];
`;
writeFileSync(FILE, body, 'utf8');
console.log(`event archive: ${list.length} events (${list.length - before} new, events from ${source})`);
